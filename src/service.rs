//! Always-on service management: install Catenary's daemon under the host's
//! per-user service manager (ws49-04).
//!
//! Under the hooks-only lifecycle the daemon no longer self-exits on an idle
//! last-client disconnect (that path retired in `router.rs` with this ticket);
//! its lifetime belongs to a service manager instead. This module installs,
//! removes, and reports on that unit:
//!
//! - **Linux** — a systemd `--user` unit at
//!   `$XDG_CONFIG_HOME/systemd/user/catenary.service`, enabled and started via
//!   `systemctl --user`.
//! - **macOS** — a per-user launchd `LaunchAgent` plist at
//!   `~/Library/LaunchAgents/dev.markwells.catenary.plist`, loaded via
//!   `launchctl`.
//!
//! Both carry `MALLOC_ARENA_MAX=2`: the ws49-02 arena receipt measured ~82 of
//! 94 MiB retained in glibc arenas after a small-allocation free (bug 136's
//! protocol-churn class), so capping the arena count bounds the resident set an
//! always-on daemon accretes. The unit/plist body carries that citation.
//!
//! The unit/plist *content* is generated by pure, platform-independent
//! functions ([`systemd_unit`], [`launchd_plist`]) so it is unit-testable on any
//! host; the install/uninstall/status/state entry points are whole-function
//! platform splits (never inner-cfg fallbacks — the ws49-01/02 macOS-clippy
//! lesson) so each platform carries exactly one real body.

use std::path::PathBuf;

use anyhow::Result;

use crate::cli::Output;

/// The systemd `--user` unit file name (Linux).
pub const SYSTEMD_UNIT_NAME: &str = "catenary.service";

/// The launchd `LaunchAgent` label / plist basename (macOS).
pub const LAUNCHD_LABEL: &str = "dev.markwells.catenary";

/// The arena-cap environment variable both units carry (bug 136 lean 3).
pub const ARENA_ENV_KEY: &str = "MALLOC_ARENA_MAX";

/// The arena-cap value: two arenas (the ws49-02 receipt's cap).
pub const ARENA_ENV_VALUE: &str = "2";

/// Renders the systemd `--user` unit body for the daemon at `exe` (Linux).
///
/// Pure and platform-independent so the content is unit-testable anywhere. The
/// `[Service]` block runs `<exe> daemon` in the foreground (`Type=simple`:
/// `catenary daemon` blocks on its accept loop and does not fork), carries the
/// arena cap with its measured citation, and restarts on failure — the service
/// manager, not the daemon, now owns the lifetime.
#[must_use]
pub fn systemd_unit(exe: &str) -> String {
    format!(
        "[Unit]\n\
         Description=Catenary code-intelligence daemon\n\
         Documentation=https://github.com/TwoWells/Catenary\n\
         After=default.target\n\
         \n\
         [Service]\n\
         Type=simple\n\
         ExecStart={exe} daemon\n\
         Restart=on-failure\n\
         RestartSec=2\n\
         # Arena cap (bug 136 lean 3). The ws49-02 arena receipt measured\n\
         # ~82 of 94 MiB retained in glibc arenas after a small-allocation\n\
         # free (the protocol-churn class bug 136 diagnosed); capping the\n\
         # arena count bounds the resident set an always-on daemon accretes.\n\
         Environment={ARENA_ENV_KEY}={ARENA_ENV_VALUE}\n\
         \n\
         [Install]\n\
         WantedBy=default.target\n",
    )
}

/// Renders the launchd `LaunchAgent` plist body for the daemon at `exe` (macOS).
///
/// Pure and platform-independent so the content is unit-testable on Linux (this
/// worker's host). `RunAtLoad` + `KeepAlive` make launchd own the lifetime —
/// the daemon is (re)started when the agent loads and kept resident. The
/// `EnvironmentVariables` dict carries the arena cap with its measured citation
/// in a leading comment.
#[must_use]
pub fn launchd_plist(exe: &str) -> String {
    format!(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n\
         <!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" \
         \"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">\n\
         <!-- {ARENA_ENV_KEY}={ARENA_ENV_VALUE}: bug 136 lean 3. The ws49-02\n\
              arena receipt measured ~82 of 94 MiB retained in glibc arenas\n\
              after a small-allocation free; the cap bounds the resident set\n\
              an always-on daemon accretes. -->\n\
         <plist version=\"1.0\">\n\
         <dict>\n\
         \t<key>Label</key>\n\
         \t<string>{LAUNCHD_LABEL}</string>\n\
         \t<key>ProgramArguments</key>\n\
         \t<array>\n\
         \t\t<string>{exe}</string>\n\
         \t\t<string>daemon</string>\n\
         \t</array>\n\
         \t<key>EnvironmentVariables</key>\n\
         \t<dict>\n\
         \t\t<key>{ARENA_ENV_KEY}</key>\n\
         \t\t<string>{ARENA_ENV_VALUE}</string>\n\
         \t</dict>\n\
         \t<key>RunAtLoad</key>\n\
         \t<true/>\n\
         \t<key>KeepAlive</key>\n\
         \t<true/>\n\
         </dict>\n\
         </plist>\n",
    )
}

/// The systemd `--user` unit path: `$XDG_CONFIG_HOME/systemd/user/catenary.service`.
///
/// Resolved through [`crate::paths::config_dir`], so an `isolate_env`-driven
/// test writes under its isolated config base — never the operator's real
/// `~/.config/systemd`.
#[must_use]
pub fn systemd_unit_path() -> PathBuf {
    crate::paths::config_dir()
        .join("systemd")
        .join("user")
        .join(SYSTEMD_UNIT_NAME)
}

/// The launchd `LaunchAgent` plist path: `~/Library/LaunchAgents/<label>.plist`.
///
/// Resolved through [`crate::paths::home_dir`], so an `isolate_env` test — which
/// points `CATENARY_HOME_DIR` at an isolated home base — never touches the
/// operator's real `~/Library`, while production lands on the real `$HOME`. The
/// `LaunchAgents` layout is fixed by launchd, so the isolation hangs it under
/// the isolated home's `Library/LaunchAgents`.
#[must_use]
pub fn launchd_plist_path() -> PathBuf {
    launchd_home()
        .join("Library")
        .join("LaunchAgents")
        .join(format!("{LAUNCHD_LABEL}.plist"))
}

/// The base directory that holds `Library/LaunchAgents` for the plist.
///
/// The home base, one resolver for every home-rooted artifact (misc 229): it
/// used to ride the *data* base's `CATENARY_DATA_DIR` override, which isolated
/// the plist correctly but spelled "home" as "data" — a mislocation the distinct
/// bases exist to catch. Kept private — callers use [`launchd_plist_path`].
fn launchd_home() -> PathBuf {
    crate::paths::home_dir().unwrap_or_else(|| PathBuf::from("."))
}

/// The absolute path to the currently-running `catenary` binary, for `ExecStart`
/// / `ProgramArguments`.
///
/// # Errors
///
/// Returns an error if the current executable path cannot be resolved.
fn daemon_exe() -> Result<String> {
    let exe =
        std::env::current_exe().map_err(|e| anyhow::anyhow!("resolve current executable: {e}"))?;
    Ok(exe.display().to_string())
}

/// A daemon's idle resident-set size in bytes, read by pid (Linux).
///
/// The ws49-02 helper's method (`/proc/<pid>/statm`, resident pages × 4 KiB),
/// parameterized by pid so `catenary doctor` — a separate process from the
/// daemon — can read the *daemon's* footprint. `None` when the pid has no
/// readable `statm` (dead, or racing teardown). Whole-function platform split
/// per the ws49-01/02 macOS-clippy lesson: the non-Linux body is a `const fn`
/// returning `None`, never an inner-cfg fallback.
#[cfg(target_os = "linux")]
#[must_use]
pub fn idle_footprint_bytes(pid: u32) -> Option<u64> {
    let statm = std::fs::read_to_string(format!("/proc/{pid}/statm")).ok()?;
    let resident_pages: u64 = statm.split_whitespace().nth(1)?.parse().ok()?;
    Some(resident_pages * 4096)
}

/// A daemon's idle resident-set size in bytes, read by pid (non-Linux).
///
/// `None` off Linux: no `/proc/<pid>/statm`. Whole-function platform split (a
/// `const fn` stub, not an inner-cfg fallback) so the macOS clippy leg sees a
/// single real body per platform (the ws49-01/02 lesson).
#[cfg(not(target_os = "linux"))]
#[must_use]
pub const fn idle_footprint_bytes(_pid: u32) -> Option<u64> {
    None
}

/// Whether the service unit/plist file is installed on disk (platform-dispatched).
///
/// Linux checks the systemd unit path; macOS checks the launchd plist path.
/// Content-only: it reports the file's presence, not whether the manager has it
/// loaded (that is [`running_state`]).
#[cfg(target_os = "linux")]
#[must_use]
pub fn is_installed() -> bool {
    systemd_unit_path().is_file()
}

/// Whether the service plist is installed on disk (macOS).
#[cfg(target_os = "macos")]
#[must_use]
pub fn is_installed() -> bool {
    launchd_plist_path().is_file()
}

/// Whether the service is installed (other platforms — never).
#[cfg(not(any(target_os = "linux", target_os = "macos")))]
#[must_use]
pub const fn is_installed() -> bool {
    false
}

/// Install and start the always-on service (Linux).
///
/// Writes the systemd `--user` unit under the isolated/real config base, then
/// `systemctl --user daemon-reload`, `enable`, and `start`. The `systemctl`
/// legs are best-effort-reported: on a host without a running user manager
/// (a CI sandbox, a headless box with no user bus) the unit is still written
/// and the failure is surfaced, not swallowed — the live leg is environment-
/// gated, the file leg always lands.
///
/// # Errors
///
/// Returns an error if the unit file cannot be written.
#[cfg(target_os = "linux")]
pub fn install(out: &mut Output) -> Result<()> {
    let exe = daemon_exe()?;
    let unit = systemd_unit(&exe);
    let path = systemd_unit_path();
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .map_err(|e| anyhow::anyhow!("create unit directory {}: {e}", parent.display()))?;
    }
    std::fs::write(&path, &unit)
        .map_err(|e| anyhow::anyhow!("write unit {}: {e}", path.display()))?;
    let _ = out.writeln(format_args!("Wrote {}", path.display()));

    // Enable + start via the user manager. Reported, not fatal: the unit file
    // is the durable artifact; a sandbox with no user bus still gets it.
    run_systemctl(out, &["daemon-reload"]);
    run_systemctl(out, &["enable", SYSTEMD_UNIT_NAME]);
    run_systemctl(out, &["start", SYSTEMD_UNIT_NAME]);
    let _ = out.writeln(format_args!(
        "Catenary service installed. `catenary service status` to check it."
    ));
    Ok(())
}

/// Install and load the always-on service (macOS).
///
/// Writes the `LaunchAgent` plist under the isolated/real base, then
/// `launchctl load`. Reported, not fatal — the plist is the durable artifact.
///
/// # Errors
///
/// Returns an error if the plist file cannot be written.
#[cfg(target_os = "macos")]
pub fn install(out: &mut Output) -> Result<()> {
    let exe = daemon_exe()?;
    let plist = launchd_plist(&exe);
    let path = launchd_plist_path();
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(|e| {
            anyhow::anyhow!("create LaunchAgents directory {}: {e}", parent.display())
        })?;
    }
    std::fs::write(&path, &plist)
        .map_err(|e| anyhow::anyhow!("write plist {}: {e}", path.display()))?;
    let _ = out.writeln(format_args!("Wrote {}", path.display()));

    run_launchctl(out, &["load", &path.display().to_string()]);
    let _ = out.writeln(format_args!(
        "Catenary service installed. `catenary service status` to check it."
    ));
    Ok(())
}

