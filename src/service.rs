/// The manager's active/loaded state, or `None` when unknowable (Linux).
///
/// Shells to `systemctl --user is-active`. `None` when the query itself cannot
/// run (no user bus, no `systemctl`), so the doctor/status line can say
/// "unknown" honestly rather than fabricate "inactive".
#[cfg(target_os = "linux")]
fn systemctl_is_active() -> Option<String> {
    let out = std::process::Command::new("systemctl")
        .args(["--user", "is-active", SYSTEMD_UNIT_NAME])
        .stdin(std::process::Stdio::null())
        .output()
        .ok()?;
    let s = String::from_utf8_lossy(&out.stdout).trim().to_string();
    (!s.is_empty()).then_some(s)
}

/// Whether the `LaunchAgent` is loaded, or `None` when unknowable (macOS).
///
/// Shells to `launchctl list <label>`: exit 0 means loaded, non-zero means not.
/// `None` when `launchctl` cannot run at all.
#[cfg(target_os = "macos")]
fn launchctl_is_loaded() -> Option<String> {
    let out = std::process::Command::new("launchctl")
        .args(["list", LAUNCHD_LABEL])
        .stdin(std::process::Stdio::null())
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .status()
        .ok()?;
    Some(if out.success() { "yes" } else { "no" }.to_string())
}

/// Runs `systemctl --user <args>`, reporting the outcome (Linux).
///
/// Best-effort: a failure (no user bus, no `systemctl`) is reported on `out`,
/// never fatal — the unit file is the durable artifact, the live leg is
/// environment-gated (CI sandboxes lack a user manager).
#[cfg(target_os = "linux")]
fn run_systemctl(out: &mut Output, args: &[&str]) {
    let mut full = vec!["--user"];
    full.extend_from_slice(args);
    match std::process::Command::new("systemctl")
        .args(&full)
        .stdin(std::process::Stdio::null())
        .output()
    {
        Ok(o) if o.status.success() => {}
        Ok(o) => {
            let stderr = String::from_utf8_lossy(&o.stderr);
            let _ = out.writeln(format_args!(
                "note: `systemctl --user {}` did not succeed ({}) — the unit \
                 file is written; run it yourself once a user manager is available",
                args.join(" "),
                stderr.trim(),
            ));
        }
        Err(e) => {
            let _ = out.writeln(format_args!(
                "note: could not run `systemctl --user {}` ({e}) — the unit file \
                 is written; the live leg is environment-gated",
                args.join(" "),
            ));
        }
    }
}

/// Runs `launchctl <args>`, reporting the outcome (macOS).
#[cfg(target_os = "macos")]
fn run_launchctl(out: &mut Output, args: &[&str]) {
    match std::process::Command::new("launchctl")
        .args(args)
        .stdin(std::process::Stdio::null())
        .output()
    {
        Ok(o) if o.status.success() => {}
        Ok(o) => {
            let stderr = String::from_utf8_lossy(&o.stderr);
            let _ = out.writeln(format_args!(
                "note: `launchctl {}` did not succeed ({}) — the plist is written",
                args.join(" "),
                stderr.trim(),
            ));
        }
        Err(e) => {
            let _ = out.writeln(format_args!(
                "note: could not run `launchctl {}` ({e}) — the plist is written",
                args.join(" "),
            ));
        }
    }
}

