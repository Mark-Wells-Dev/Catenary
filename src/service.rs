/// Print the service's honest state in both installed and absent cases
/// (platform-dispatched).
///
/// Names the manager, the unit/plist path, whether it is installed, and — best
/// effort — whether the manager reports it active. The active check rides the
/// manager's own query (`systemctl --user is-active` / `launchctl list`); its
/// unavailability (no user bus) is reported as "unknown", never faked.
///
/// # Errors
///
/// Never fails — status is a read.
#[cfg(target_os = "linux")]
pub fn status(out: &mut Output) -> Result<()> {
    let path = systemd_unit_path();
    let _ = out.writeln(format_args!("Manager:   systemd --user"));
    let _ = out.writeln(format_args!("Unit:      {}", path.display()));
    if is_installed() {
        let _ = out.writeln(format_args!("Installed: yes"));
        let active = systemctl_is_active();
        let _ = out.writeln(format_args!(
            "Active:    {}",
            active.as_deref().unwrap_or("unknown")
        ));
    } else {
        let _ = out.writeln(format_args!("Installed: no"));
        let _ = out.writeln(format_args!(
            "Run `catenary service install` to run the daemon under systemd."
        ));
    }
    Ok(())
}

