use crate::cli::Output;

/// Annotated recommended config template.
///
/// This is a curated TOML document with comments explaining each entry,
/// not generated from structs. Users redirect this to their config file.
/// The target path depends on `XDG_CONFIG_HOME` (Linux: `~/.config`,
/// macOS: `~/Library/Application Support`, Windows: `AppData/Roaming`).
const TEMPLATE: &str = r#"#:schema https://twowells.github.io/catenary/schemas/config.json
# Catenary recommended config
# Generated by `catenary config`. Edit to match your workflow.
#
# The `#:schema` directive above associates this file with Catenary's published
# JSON Schema — taplo, tombi, and other schema-aware TOML tools honor it for
# live validation and completion. Catenary also associates the schema
# automatically at the TOML server it spawns; the directive covers editors it
# does not serve.
#
# Config sources (later overrides earlier):
#   1. <XDG_CONFIG_HOME>/catenary/config.toml  (this file)
#   2. .catenary.toml                          (project-local)
#   3. CATENARY_CONFIG env var                 (explicit override)
#
# XDG_CONFIG_HOME defaults:
#   Linux:   ~/.config
#   macOS:   ~/Library/Application Support
#   Windows: C:\Users\<user>\AppData\Roaming

# ── Command filtering ────────────────────────────────────────────
#
# Allowlist-based: only explicitly permitted commands can run.
# Everything else is denied with a dump of the allowed config.
#
# Three states:
#   1. No [commands] section         — not configured (hint notification)
#   2. client_enforcement_only=true  — deliberate opt-out, no enforcement
#   3. allow = [...] present         — active allowlist
#
# Keys:
#   build    — project build tool (e.g., "make"). Set per-project in
#              .catenary.toml so the agent uses the build system.
#   allow    — commands the agent can run unconditionally.
#   pipeline — commands allowed mid-pipeline (reading stdin), denied
#              at pipeline position 0 (reading files directly).
#   deny.*   — subcommand denylist within an allowed command.
#
# Writes resolve-or-deny: a redirect (`>`/`>>`/`&>`) or a `cp`/`mv`/
# `tee`/`sed -i`/`git apply` write is allowed when the hook can see its
# complete target set (recorded for the diagnostics batch), and denied
# with a teaching message when it can't. fd-dups (`2>&1`, `>&2`) and
# device sinks (`/dev/null`, ...) are never writes.
#
# Uncomment the [commands] section below to activate.

# [commands]
# # client_enforcement_only = true
# build = "make"
# # Build-command alternatives — pick the one your ecosystem uses. `build`
# # is a single value, so keep exactly one active line (above) and leave the
# # rest commented; set it per-project in .catenary.toml. Uncomment one:
# #   build = "just"
# #   build = "cargo"
# #   build = "npm"
# #   build = "yarn"
# #   build = "pnpm"
# #   build = "go"
# #   build = "gradle"
# #   build = "mvn"
# #   build = "cmake"
# # `allow` includes read/stdout-only tools (cat, head, less, diff,
# # echo, ...): reads aren't a write vector, and a redirected write
# # (`cat > f`) is resolved and attributed, not blocked by denying cat.
# # `sed` and `perl` are allowed as bulk writers: their in-place edits
# # (`sed -i`, `perl -i -pe`) are script-checked and resolved into the
# # diagnostics batch, and an unparseable/executing script (`sed -i 'w …'`,
# # `perl -e system(…)`) is surgically denied by the resolver.
# allow = ["git", "gh", "cp", "rm", "mkdir", "mv", "touch",
#          "chmod", "sleep", "cd", "true", "false", "which",
#          "cat", "head", "tail", "less", "more", "diff",
#          "echo", "printf", "seq", "sed", "perl"]
# pipeline = ["grep", "wc", "jq", "sort", "tr", "cut", "uniq"]
#
# [commands.deny]
# git = ["grep", "ls-files", "ls-tree"]
# sqlite3 = ["-cmd"]
#
# [commands.deny_flags]
# # These deny the flags that redirect the tool to operate outside the project root
# # — adapt to your ecosystem. make/cargo below are the shipped pair; uncomment
# # the line for whatever `build` you set above (and drop the others).
# make = ["-C"]
# cargo = ["--manifest-path"]
# #   npm    = ["--prefix"]                    # --prefix (alias -C) runs npm elsewhere
# #   yarn   = ["--cwd"]                        # --cwd sets the working directory
# #   pnpm   = ["-C", "--dir"]                  # -C / --dir run pnpm elsewhere
# #   go     = ["-C"]                           # -C dir: chdir before the command
# #   gradle = ["-p", "--project-dir"]          # -p / --project-dir set the start dir
# #   mvn    = ["-f", "--file"]                 # -f / --file: alternate POM / dir
# #   just   = ["-f", "--justfile", "-d", "--working-directory"]  # justfile + working dir
# #   cmake  = ["-S", "-B"]                     # -S source dir / -B build dir
#
# # allow_flags — the allow-side dual of deny_flags: a keyed command must be
# # invoked in one of the listed forms or it is denied naming them. Forms are
# # positive anchors: `-pe` matches any invocation carrying both `-p` and `-e`.
# # Listing a form can only narrow, never re-open: the write auditor still
# # runs on whatever passes the form gate. For perl that means a script file
# # (`perl script.pl` — even behind an allowed `-i`) stays denied because the
# # hook can't see the program, and a literal `-e` program must be a
# # recognizable substitution (`s///`, `tr///`, `y///`) to run. Net effect of
# # the entry below: perl is available as a nicer sed, nothing more.
# [commands.allow_flags]
# perl = ["-i", "-pe", "-e"]
#
# # script_hosts — the opt-in above the form gate: it lets a modeled
# # substitution engine (perl/awk/sed) run its unseeable script-file form as a
# # full script host — the executor boundary, like `python script.py` — instead
# # of the default soundness denial. Inline programs keep their substitution
# # audit; only the script-file / stdin shape relaxes. Layering is default deny
# # -> script_hosts (executor boundary) -> allow_flags (narrowing). A command
# # can't be in both script_hosts and allow_flags (a flagless script matches no
# # form anchor), so drop the allow_flags entry to make it a script host.
# # script_hosts = ["perl"]
#
# # Per-command guidance — optional hints shown when a command is denied.
# # Groups map commands to a message. {EDIT} resolves per-client.
#
# [commands.guidance.scan]
# redirect = "grep"
# commands = ["rg", "ag", "ack", "fd", "grep", "egrep",
#             "fgrep", "rgrep", "zgrep"]
#
# [commands.guidance.list]
# redirect = "glob"
# commands = ["ls", "dir", "tree", "find"]
#
# [commands.guidance.build]
# commands = ["cargo", "rustc", "rustup", "npm", "npx", "yarn",
#             "pnpm", "go", "gradle", "mvn", "cmake", "pip",
#             "poetry", "pytest", "prettier"]

# ── Project-local overrides (.catenary.toml) ─────────────────────
#
# A project .catenary.toml honors `build` only. Every other [commands]
# key — client_enforcement_only, allow, pipeline, deny, deny_flags,
# allow_flags, script_hosts — is
# user-level only: the filter resolves daemon-globally (one daemon serves
# every session), so a project can neither relax it nor turn it on/off for
# itself. Those keys are ignored (with a warning) in project config — keep
# them here in user config.
#
#   # Set the build tool for this project
#   [commands]
#   build = "make"
#
#   # Disable Catenary LSP for this workspace entirely
#   # (the project build tool still applies)
#   [lsp]
#   disable = true

# ── Notifications ────────────────────────────────────────────────
#
# desktop: OS-level desktop notifications for error-severity events —
# the urgent interrupt. Warns persist on the TUI health dashboard and
# everything is queryable via `catenary query`, so there is no severity
# threshold to set.
# Set desktop to false to suppress. The CATENARY_NOTIFY env var also suppresses
# when set to an off value (0/off/false/no).

# [notifications]
# desktop = true

# ── Server environment ────────────────────────────────────────────
#
# Per-server environment variables. Added to the inherited
# environment (config value wins on conflict).
#
# [lsp.server.rust-analyzer]
# env = { CLIPPY_DISABLE_DOCS_LINKS = "1" }

# ── Root markers ──────────────────────────────────────────────────
#
# Root markers define project boundaries within workspace roots.
# Catenary walks up from each file, stopping at the first directory
# containing any marker. That directory becomes the server's root.
# Different resolved roots get separate server instances.
#
# Defaults are shipped for common languages (rust = ["Cargo.toml"],
# go = ["go.mod"], python = ["pyproject.toml", ...], etc.). Override
# per-language, or disable with an empty list.
#
# Entries can be exact filenames or glob patterns (*, ?, []).
# Exact filenames use a fast exists() check; globs read directory
# entries and match against compiled patterns.
#
# [lsp.language.rust]
# root_markers = ["rust-toolchain.toml"]   # custom markers
#
# [lsp.language.csharp]
# root_markers = ["*.sln", "*.csproj"]     # glob patterns
#
# [lsp.language.python]
# root_markers = []                        # disable for python

# ── Companion roots ──────────────────────────────────────────────
#
# [roots.companions] auto-mounts a derived sibling root alongside each
# workspace root a host declares — so opening a project also mounts its
# planning/companion repo for LSP intelligence, no manual `catenary pin`.
#
# OFF BY DEFAULT and USER-CONFIG ONLY: Catenary ships no table and assumes no
# naming convention (an active `"*" = "{root}Internal"` would auto-mount
# strangers' coincidentally-named siblings). It is read only from this user
# config, never from a project `.catenary.toml` — a public repo must not be
# able to leak a private sibling path. The example below is a template only;
# uncomment to enable.
#
# [roots.companions]
# "*"                  = "{root}Internal"          # any root → its <path>Internal sibling
# "~/Projects/homelab" = "~/.local/share/chezmoi"  # explicit, unrelated path

# ── Tools (`catenary grep`/`glob`/`diagnostics`) ─────────────────
#
# Every command emits its COMPLETE output (decision 025): no line budget, no
# paging, no spill file — the host caps only the final read at the end of a
# pipeline. There is no volume knob to configure.

# [tools.glob]
# outline_suppress: glob patterns whose outlines are hidden from automatic
#   display (symbols stay available via `catenary glob <file>`). Default: none.
# outline_suppress = ["**/*.min.js"]

# ── Diagnostics (`catenary diagnostics`) ─────────────────────────
#
# diagnostics_severity: the minimum severity that labels a run "dirty" (vs
#   "clean") — one of error, warning, info, hint. Default "error". A status
#   label only: the run always exits 0 and prints every diagnostic.

# [tools]
# diagnostics_severity = "error"
"#;

/// Print the recommended config template to stdout.
///
/// Appends a built-in server defaults reference section generated from
/// the embedded `defaults/servers.toml`.
pub fn print_template(out: &mut Output) {
    let _ = out.write_str(format_args!("{TEMPLATE}"));
    let _ = out.write_str(format_args!("{}", generate_defaults_section()));
    let _ = out.write_str(format_args!("{}", generate_linter_defaults_section()));
}

/// Generate a commented-out reference section listing all built-in
/// server defaults.
///
/// Each `[lsp.server.*]` entry from `defaults/servers.toml` is rendered as
/// a comment block so users can discover canonical names and override
/// selectively.
fn generate_defaults_section() -> String {
    use std::fmt::Write;

    let mut out = String::new();
    let _ = writeln!(
        out,
        "\n# ── Built-in Server Defaults ──────────────────────────────────"
    );
    let _ = writeln!(
        out,
        "# Catenary ships default definitions for these servers. Reference"
    );
    let _ = writeln!(
        out,
        "# one by name in a [lsp.language.*] servers list and it works without"
    );
    let _ = writeln!(
        out,
        "# a [lsp.server.*] entry. To override, uncomment and modify."
    );

    for line in crate::config::DEFAULT_SERVERS.lines() {
        if line.is_empty() {
            let _ = writeln!(out, "#");
        } else if line.starts_with('#') {
            // Preserve original comment lines (section headers).
            let _ = writeln!(out, "# {line}");
        } else {
            let _ = writeln!(out, "# {line}");
        }
    }

    out
}

/// Generate a commented-out reference section listing all built-in linter
/// defaults.
///
/// Each `[linter.rule.*]` entry from `defaults/linters.toml` is rendered as a
/// comment block so users can discover the shipped linters and override or
/// disable one selectively — the linter analogue of
/// [`generate_defaults_section`].
fn generate_linter_defaults_section() -> String {
    use std::fmt::Write;

    let mut out = String::new();
    let _ = writeln!(
        out,
        "\n# ── Built-in Linter Defaults ──────────────────────────────────"
    );
    let _ = writeln!(
        out,
        "# Catenary runs these standalone linters during `catenary diagnostics`"
    );
    let _ = writeln!(
        out,
        "# when the tool is installed (skipped otherwise). A [linter.rule.*] entry"
    );
    let _ = writeln!(
        out,
        "# with the same name replaces the default wholesale; set disable = true"
    );
    let _ = writeln!(out, "# to turn one off.");

    for line in crate::config::DEFAULT_LINTERS.lines() {
        if line.is_empty() {
            let _ = writeln!(out, "#");
        } else {
            let _ = writeln!(out, "# {line}");
        }
    }

    out
}

/// Test-only access to the recommended `[commands]` config embedded in
/// [`TEMPLATE`]. The single source of truth for the shipped default
/// command-filter config: this module's own tests *and* `command_filter`'s
/// behavioral tests both derive from it, so neither hand-maintains a mirror
/// that could drift from the template.
#[cfg(test)]
#[allow(
    clippy::expect_used,
    reason = "test-only helper; expect gives a readable failure"
)]
pub(crate) mod test_recommended {
    use crate::config::CommandsConfig;

    /// The commented-out `[commands]` block from [`super::TEMPLATE`] (between
    /// `# [commands]` and the next section separator), uncommented.
    pub fn block() -> String {
        let mut in_block = false;
        let mut lines = Vec::new();
        for line in super::TEMPLATE.lines() {
            if line == "# [commands]" {
                in_block = true;
            } else if in_block && line.starts_with("# ── ") {
                break;
            }
            if in_block {
                lines.push(
                    line.strip_prefix("# ")
                        .unwrap_or(if line == "#" { "" } else { line }),
                );
            }
        }
        lines.join("\n")
    }

    /// Parse the recommended `[commands]` block into a [`CommandsConfig`].
    pub fn config() -> CommandsConfig {
        #[derive(serde::Deserialize)]
        struct Wrapper {
            commands: CommandsConfig,
        }
        let wrapper: Wrapper =
            toml::from_str(&block()).expect("recommended [commands] block is valid TOML");
        wrapper.commands
    }
}

